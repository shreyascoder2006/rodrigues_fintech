function synthesizeSeries(end: number, points: number, volatility: number, trend: number): PortfolioSnapshot[] {
  const series: number[] = new Array(points)
  series[points - 1] = end
  let v = end
  for (let i = points - 2; i >= 0; i--) {
    const wave = Math.sin(i * 0.9) * volatility
    v = v / (1 + trend / points) - wave
    series[i] = Math.max(v, end * 0.4)
  }
  const today = new Date()
  return series.map((value, i) => {
    const d = new Date(today)
    d.setDate(d.getDate() - (points - 1 - i) * 7)
    return { date: d.toISOString(), value: Math.round(value) }
  })
}

